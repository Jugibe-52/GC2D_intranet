"""Guiding-centre physical dynamics independent of initial conditions."""

from __future__ import annotations

from dataclasses import dataclass
from functools import lru_cache
from typing import Any, ClassVar, TYPE_CHECKING

import numpy as np

from potential.potential import Potential

from dynamics.coordinates import GCCoordinates


if TYPE_CHECKING:
	from dynamics.jax_dynamics import JaxGuidingCenterDynamics
	from contracts.arrays import BackendArray
	from types import ModuleType


def _validated_parameters(potential: Potential, rho: float, B: float) -> tuple[float, float]:
	"""Normalize physical parameters in their established validation order."""
	if not isinstance(potential, Potential):
		raise TypeError("`potential` must be a Potential instance.")
	B = float(B)
	if not np.isfinite(B) or B == 0:
		raise ValueError("`B` must be finite and non-zero.")
	rho = float(rho)
	if not np.isfinite(rho) or rho < 0:
		raise ValueError("`rho` must be finite and non-negative.")
	return rho, B


@dataclass(frozen=True, init=False, eq=False)
class GuidingCenterDynamics:
	"""GC equations generated by the prepared Hamiltonian H = Phi_rho / B."""

	coordinates: ClassVar[GCCoordinates] = GCCoordinates()
	state_dimension: ClassVar[int] = 2

	potential: Potential
	rho: float
	B: float
	hamiltonian_potential: Potential

	@lru_cache(maxsize=16)
	def _as_jax(self) -> JaxGuidingCenterDynamics:
		"""Prepare physical components once without rebuilding or mutating them."""
		from dynamics.jax_dynamics import JaxGuidingCenterDynamics
		if type(self) not in (GuidingCenterDynamics, JaxGuidingCenterDynamics):
			raise TypeError("JAX preparation requires built-in dynamics; subclass overrides are not compiled.")
		potential: Potential = self.potential._as_jax()
		hamiltonian: Potential = self.hamiltonian_potential._as_jax()
		if type(self) is JaxGuidingCenterDynamics and potential is self.potential and hamiltonian is self.hamiltonian_potential:
			return self
		prepared: JaxGuidingCenterDynamics = object.__new__(JaxGuidingCenterDynamics)
		prepared.__dict__.update(self.__dict__)
		object.__setattr__(prepared, "potential", potential)
		object.__setattr__(prepared, "hamiltonian_potential", hamiltonian)
		return prepared

	def __init__(self, potential: Potential, *, rho: float = 0.0, B: float = 1.0) -> None:
		"""Create GC dynamics for a runtime Larmor radius and signed magnetic field."""
		rho, B = _validated_parameters(potential, rho, B)
		object.__setattr__(self, "potential", potential)
		object.__setattr__(self, "rho", rho)
		object.__setattr__(self, "B", B)
		averaged: Potential = potential.gyroaverage(rho)
		# H=P/B drives all equations, including Jacobians and time derivatives.
		if B != 1.0:
			averaged = type(averaged)(averaged.grid, mean=averaged.mean / B,
				modes=averaged.modes / B, frequencies=averaged.frequencies,
				interpolation_order=averaged.interpolation_order)
		object.__setattr__(self, "hamiltonian_potential", averaged)

	def vector_field(self, t: Any, state: Any) -> Any:
		"""Evaluate GC drift at one time or broadcast times over a packed history."""
		x: BackendArray
		y: BackendArray
		x, y = self.coordinates.split(state)
		dh_dx: BackendArray = self.hamiltonian_potential.evaluate(t, x, y, dx=1)
		dh_dy: BackendArray = self.hamiltonian_potential.evaluate(t, x, y, dy=1)
		return self.coordinates.pack_components(-dh_dy, dh_dx)

	def particle_vector_field_jacobians(
		self,
		t: Any,
		state: Any,
	) -> Any:
		"""Return one exact two-by-two spatial Jacobian per GC particle.

		For ``N`` particles the packed state is ``[x_1, ..., x_N, y_1, ...,
		y_N]`` and the result has shape ``(N, 2, 2)``. Particles are uncoupled
		by the field evaluation, so this batched representation avoids assembling
		a sparse ``(2N, 2N)`` matrix. With ``f = (-H_y, H_x)``, the rows are
		``(-H_xy, -H_yy)`` and ``(H_xx, H_xy)``.
		"""
		x: BackendArray
		y: BackendArray
		x, y = self.coordinates.split(state)
		hamiltonian: Potential = self.hamiltonian_potential
		if hamiltonian.interpolation_order < 3:
			raise ValueError(
				"Exact GC vector-field Jacobians require interpolation_order >= 3."
			)
		h_xx: BackendArray = hamiltonian.evaluate(t, x, y, dx=2)
		h_xy: BackendArray = hamiltonian.evaluate(t, x, y, dx=1, dy=1)
		h_yy: BackendArray = hamiltonian.evaluate(t, x, y, dy=2)
		xp: ModuleType = self.coordinates.array_namespace
		return xp.stack(
			(
				xp.stack((-h_xy, -h_yy), axis=-1),
				xp.stack((h_xx, h_xy), axis=-1),
			),
			axis=-2,
		)

	def hamiltonian(
		self,
		t: Any,
		state: Any,
	) -> Any:
		"""Evaluate gyroaveraged Hamiltonian values."""
		x: BackendArray
		y: BackendArray
		x, y = self.coordinates.split(state)
		return self.hamiltonian_potential.evaluate(t, x, y)

	def hamiltonian_time_derivative(
		self,
		t: Any,
		state: Any,
	) -> Any:
		"""Evaluate positive partial_t H in the physical Hamiltonian normalization."""
		x: BackendArray
		y: BackendArray
		x, y = self.coordinates.split(state)
		return self.hamiltonian_potential.evaluate(
			t,
			x,
			y,
			dt=1,
		)

	def extended_momentum_derivative(self, t: Any, state: Any) -> Any:
		"""Return -partial_t H for specialized time-extended diagnostics."""
		return -self.hamiltonian_time_derivative(t, state)



__all__ = ["GuidingCenterDynamics"]
